import assert from 'node:assert/strict';
import {anchorValue,featureCenter,featureLoops,localFeatureLoops,measureFeature} from '../surface-editor.mjs';
assert.equal(anchorValue('start',4,10,90),14);
assert.equal(anchorValue('end',4,10,90),86);
assert.equal(anchorValue('center',-5,10,90),45);
assert.equal(anchorValue('relative',.25,10,90),30);
const feature={shape:'rect',width:20,height:10,x:4,y:8,angle:90,anchor:{u:'center',v:'start'}};
assert.deepEqual(featureCenter(feature,[0,0,200,100]),[104,8]);
const points=featureLoops(feature,[0,0,200,100])[0];
assert.ok(Math.abs(points[0][0]-109)<1e-9);
assert.ok(Math.abs(points[0][1]+2)<1e-9);
const pattern=localFeatureLoops({...feature,shape:'pattern',count:3,pitch:12,width:4});
assert.equal(pattern.length,3);
assert.equal(pattern[0][0][0],-10);
assert.equal(pattern[2][0][0],14);
const svg={...feature,shape:'svg',contours:[[[-20,-10],[20,-10],[20,10],[-20,10]]]};
assert.deepEqual(localFeatureLoops(svg),svg.contours);
const circle=localFeatureLoops({...feature,shape:'circle',width:12})[0];
assert.ok(circle.every(([x,y])=>Math.abs(Math.hypot(x,y)-6)<1e-9));
// Dimensions follow local contours even when they are rotated or edited freely.
const measured=measureFeature(feature,[0,0,200,100]);
assert.equal(measured.width,20);assert.equal(measured.height,10);
assert.equal(measured.x,104);assert.equal(measured.y,8);
assert.deepEqual(measured.center,[104,8]);
assert.ok(Math.abs(measured.corners[0][0]-109)<1e-9);
assert.ok(Math.abs(measured.corners[0][1]+2)<1e-9);
const polygon=measureFeature({...feature,shape:'polygon',points:[[-7,-4],[25,-4],[0,8]],width:20,height:10},[10,20,210,120]);
assert.equal(polygon.width,32);assert.equal(polygon.height,12);
assert.equal(measureFeature({...feature,shape:'pattern',width:5,count:3,pitch:12},[0,0,200,100]).width,29);
const anchored=measureFeature({...feature,anchor:{u:'relative',v:'end'},x:.25,y:7},[10,20,210,120]);
assert.equal(anchored.x,50);assert.equal(anchored.y,93);
const engraving=measureFeature({...feature,shape:'svg',contours:[],lines:[[[-3,0],[17,8]]]},[0,0,200,100]);
assert.equal(engraving.width,20);assert.equal(engraving.height,8);
console.log('Surface geometry checks passed.');
