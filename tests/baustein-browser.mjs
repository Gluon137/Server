// Run through playwright-cli run-code, passing the current local studio page.
export default async function checkStudio(page,baseUrl='http://127.0.0.1:8765') {
  const output='output/playwright';
  const check=(ok,message='Browser assertion failed')=>{if(!ok)throw new Error(message);};
  const assert={equal:(a,b,message)=>check(a===b,message??`${a} != ${b}`),deepEqual:(a,b,message)=>check(JSON.stringify(a)===JSON.stringify(b),message??'Different values'),ok:check,match:(s,r)=>check(r.test(s),'Expected pattern '+r),doesNotMatch:(s,r)=>check(!r.test(s),'Unexpected pattern '+r)};
  const errors=[];
  page.on('pageerror',error=>errors.push(error.message));
  await page.goto(baseUrl+'/baustein-studio/');
  await page.evaluate(()=>localStorage.removeItem('baustein-studio-project-v1'));
  await page.reload();
  const ready=()=>page.waitForFunction(()=>!document.querySelector('#downloadSVG').disabled,{},{timeout:30000});
  const saved=()=>page.evaluate(()=>JSON.parse(localStorage.getItem('baustein-studio-project-v1')));
  await ready();
  assert.equal(await page.locator('#metricPanels').innerText(),'6');
  await page.locator('[data-add="x:1"]').click();
  await ready();
  await page.locator('#dim-x').fill('80');
  await ready();
  await page.locator('#cellSelect').selectOption('0,0,0');
  await page.locator('[data-add="y:1"]').click();
  await ready();
  await page.locator('#dim-y').fill('70');
  await ready();
  assert.equal(await page.locator('#metricPanels').innerText(),'8');
  assert.deepEqual((await saved()).axes,{x:[100,80],y:[100,70],z:[100]});
  await page.locator('#faceSelect').selectOption('0,1,0:z:1');
  await page.locator('#toggleFace').click();
  await ready();
  assert.equal(await page.locator('#metricPanels').innerText(),'7');
  assert.equal((await saved()).openFaces.length,3);
  await page.locator('#undo').click();
  await ready();
  assert.equal(await page.locator('#metricPanels').innerText(),'8');
  await page.locator('#redo').click();
  await ready();
  assert.equal(await page.locator('#metricPanels').innerText(),'7');
  await page.locator('#toggleFace').click();
  await ready();
  await page.locator('#burn').fill('0.08');
  await ready();
  await page.locator('#play').fill('0.1');
  await ready();
  await page.locator('#dim-y').fill('-1');
  assert.equal(await page.locator('#downloadSVG').isDisabled(),true);
  await page.locator('#dim-y').fill('70');
  await ready();
  const project=(await saved());
  const projectDownload=page.waitForEvent('download');
  await page.locator('#saveProject').click();
  await (await projectDownload).saveAs(output+'/baustein-example-project.json');
  const malformed={...project,axes:{...project.axes,x:[0]}};
  await page.evaluate(malformed=>{const transfer=new DataTransfer();transfer.items.add(new File([JSON.stringify(malformed)],'invalid.json',{type:'application/json'}));const input=document.querySelector('#projectFile');input.files=transfer.files;input.dispatchEvent(new Event('change',{bubbles:true}));},malformed);
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Projekt nicht geladen'));
  assert.deepEqual(await saved(),project,'Invalid imports preserve the previous autosave');
  await page.reload();
  await ready();
  assert.deepEqual(await saved(),project,'Reload restores the previous project');
  await page.locator('[data-view="layout"]').click();
  assert.equal(await page.locator('#layoutPreview svg path').count(),8);
  assert.equal(await page.locator('#layoutPreview g[data-preview-only]').count(),8);
  assert.equal(await page.locator('#layoutPreview text[data-preview-only]').count(),16);
  const svgDownload=page.waitForEvent('download');
  await page.locator('#downloadSVG').click();
  const svgPath=output+'/baustein-example-cut.svg';
  await (await svgDownload).saveAs(svgPath);
  const svg=await page.locator('#layoutPreview svg').evaluate(el=>{const copy=el.cloneNode(true);copy.querySelectorAll('[data-preview-only]').forEach(node=>node.remove());return copy.outerHTML;});
  assert.match(svg,/width="600mm"/);
  assert.match(svg,/height="400mm"/);
  assert.doesNotMatch(svg,/<(?:text|script|image)\b/);
  await page.locator('[data-view="assembly"]').click();
  await page.locator('#assemblyStep').fill('0');
  await page.locator('[data-camera="fit"]').click();
  await page.screenshot({path:output+'/baustein-montage.png',scale:'css'});
  await page.locator('#assemblyPlay').click();
  await page.waitForFunction(()=>Number(document.querySelector('#assemblyStep').value)>0);
  await page.locator('#assemblyPlay').click();
  await page.locator('[data-view="layout"]').click();
  await page.screenshot({path:output+'/baustein-layout.png',scale:'css'});

  let busyCount=0;
  await page.route('**/api/build',async route=>{
    if(++busyCount<=5)await route.fulfill({status:429,contentType:'application/json',body:JSON.stringify({valid:false,errors:[{code:'BUSY',message:'Test: beschäftigt'}]})});
    else await route.continue();
  });
  await page.locator('#burn').fill('0.09');
  await ready();
  assert.ok(busyCount>=6,'Busy retries continue beyond the old 1.2-second limit');
  await page.unroute('**/api/build');
  await page.route('**/api/build',route=>route.fulfill({status:422,contentType:'application/json',body:JSON.stringify({valid:false,errors:[{code:'TIMEOUT',message:'Test: Entwurf vereinfachen'}]})}));
  await page.locator('#burn').fill('0.1');
  await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Test: Entwurf vereinfachen'));
  assert.equal(await page.locator('#serviceNote').isVisible(),false);
  assert.equal(await page.locator('#downloadSVG').isDisabled(),true);
  await page.unroute('**/api/build');
  await page.locator('#buildRetry').click();
  await ready();

  let first=true;
  await page.route('**/api/build',async route=>{
    if(first){first=false;await new Promise(resolve=>setTimeout(resolve,1200));try{await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({valid:false,errors:[{code:'STALE',message:'ALTES_ERGEBNIS'}],panels:[],assembly:[],sheets:[]})});}catch{}}
    else await route.continue();
  });
  const firstRequest=page.waitForRequest('**/api/build');
  await page.locator('#burn').fill('0.11');
  await firstRequest;
  await page.locator('#burn').fill('0.12');
  await ready();
  await new Promise(resolve=>setTimeout(resolve,1400));
  assert.doesNotMatch(await page.locator('#status').innerText(),/ALTES_ERGEBNIS/);
  assert.equal((await saved()).joint.burn,.12);
  await page.unroute('**/api/build');

  await page.locator('#reset').click();
  await ready();
  await page.locator('#width').fill('130');
  await ready();
  await page.locator('#height').fill('130');
  await ready();
  assert.equal(await page.locator('#metricSheets').innerText(),'6');
  await page.locator('#sheetSelect').selectOption('5');
  const lastSheetDownload=page.waitForEvent('download');
  await page.locator('#downloadSVG').click();
  const lastSheet=await lastSheetDownload;
  assert.equal(lastSheet.suggestedFilename(),'Baustein-Studio-Platte-6.svg');
  await lastSheet.saveAs(output+'/baustein-example-sheet-6.svg');
  await page.locator('#reset').click();
  await ready();
  await page.locator('[data-view="model"]').click();
  await page.locator('[data-tool="add"]').click();
  await page.locator('#sceneHost canvas').click();
  await ready();
  assert.equal((await saved()).cells.length,2,'Canvas raycast attaches a block');
  const canvas=await page.locator('#sceneHost canvas').boundingBox();
  await page.mouse.move(canvas.x+canvas.width/2,canvas.y+canvas.height/2);
  await page.mouse.down();
  await page.mouse.move(canvas.x+canvas.width/2+60,canvas.y+canvas.height/2+20,{steps:6});
  await page.mouse.up();
  assert.equal((await saved()).cells.length,2,'Camera drag does not edit the model');
  await page.locator('#reset').click();
  await ready();
  await page.locator('[data-tool="select"]').click();
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>scrollTo(0,0));
  await page.screenshot({path:output+'/baustein-desktop.png',scale:'css'});
  for(const width of [390,320]){
    await page.setViewportSize({width,height:844});
    await page.evaluate(()=>scrollTo(0,0));
    const dimensions=await page.evaluate(()=>[innerWidth,document.documentElement.scrollWidth]);
    assert.ok(dimensions[1]<=dimensions[0],`No horizontal overflow at ${width}px`);
    await page.screenshot({path:output+`/baustein-mobile-${width}.png`,fullPage:true,scale:'css'});
  }
  await page.setViewportSize({width:1440,height:1000});
  await page.evaluate(()=>scrollTo(0,0));
  await page.evaluate(()=>localStorage.setItem('baustein-studio-project-v1','damaged-autosave'));
  await page.reload();
  await ready();
  assert.equal(await page.evaluate(()=>localStorage.getItem('baustein-studio-project-v1')),'damaged-autosave');
  assert.match(await page.locator('#saveStatus').innerText(),/beschädigte/);
  await page.locator('#reset').click();
  await ready();
  assert.deepEqual(errors,[],'No browser script errors');
  return {passed:true,checks:'L-Modell, Öffnen, Maße, Undo/Redo, Autosave, Import, echte Downloads, Montage, 429/422, veraltete Antworten, 3D-Klick/Drag, 390/320px',consoleErrors:errors};
}
