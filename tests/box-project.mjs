import assert from 'node:assert/strict';
import {defaults,clone,validateProject,STORAGE_KEY} from '../website/box-studio/project.mjs';
assert.match(STORAGE_KEY,/box-studio/);
const p=validateProject(clone(defaults));
assert.equal(p.box.width,200);
assert.deepEqual(validateProject(JSON.parse(JSON.stringify(p))),p);
const part={id:'my-board',name:'Brett',kind:'custom',host:'bottom',shape:'rect',width:80,height:40};
p.parts.push(part);
p.features.push({id:'hole',partId:'my-board',shape:'circle',operation:'cut',width:10,height:10,anchor:{u:'relative',v:'end'},x:.25,y:12});
const valid=validateProject(p);
assert.equal(valid.features[0].anchor.u,'relative');
assert.deepEqual(valid.parts[0].rotation,[0,0,0]);
assert.equal(valid.parts[0].motion.type,'fixed');
const bad=fn=>{const data=clone(valid);fn(data);assert.throws(()=>validateProject(data));};
bad(d=>d.material.burn=NaN);
bad(d=>d.box.width=Infinity);
bad(d=>d.layout.rotate='true');
bad(d=>d.parts.push({...part}));
bad(d=>d.parts[0].host='my-board');
bad(d=>d.parts[0].motion={type:'slider',axis:[0,0,0]});
bad(d=>d.parts[0].motion={type:'slider',min:20,max:10,value:15});
bad(d=>d.features[0].points=[[1,Infinity]]);
bad(d=>d.features[0].count=2.2);
bad(d=>{d.box.shape='cylinder';d.box.lid='sliding';});
bad(d=>{d.parts.push({...part,id:'other',host:'my-board'});d.parts[0].host='other';});
bad(d=>{d.groups=[{id:'g1',partIds:['my-board']},{id:'g2',partIds:['my-board']}];});
bad(d=>{d.groups=[{id:'g1',partIds:['my-board']}];d.parts[0].motion={type:'slider',max:10};});
// A removed face is a repairable dependency error and must still be saveable.
const unresolved=clone(valid);unresolved.parts[0].host='deleted-face';
assert.equal(validateProject(unresolved).parts[0].host,'deleted-face');
const sanitized=validateProject({...valid,executable:'ignore',box:{...valid.box,untrusted:'ignore'}});
assert.ok(!('executable' in sanitized));assert.ok(!('untrusted' in sanitized.box));
const original=clone(valid);const imported=validateProject(original);imported.box.width=220;assert.equal(original.box.width,200);
console.log('Box project: round-trip, dependency cycles, invalid imports, anchors, groups and sanitization passed.');
